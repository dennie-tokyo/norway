    public function getPhotos($key, $no){
        
        $collection = collect();
        
        switch ($key){
            case "departure":
                $collection = $this->departure($collection);
                break;
            case "oslo":
                $collection = $this->oslo($collection);
                break;
            case "trollstigen":
                $collection = $this->troll($collection);
                break;
            case "geirangerfjord":
                $collection = $this->geiranger($collection);
                break;
            case "briksdalsbreen":
                $collection = $this->briksdalsbreen($collection);
                break;
            case "sognefjord":
                $collection = $this->sogne($collection);
                break;
            case "stavanger":
                $collection = $this->stavanger($collection);
                break;
            case "lysefjord":
                $collection = $this->lyse($collection);
                break;
            case "other":
                $collection = $this->other($collection);
                break;
            case "all":
                $collection = $this->all($collection);
                break;
            default:
                break;
        }
        
        $rePhotos = "";
        $cnt = 1;
        foreach ($collection->chunk(24) as $photos){

            //指定された数を返却する
            if(intval($no) === $cnt){
                $rePhotos = $photos;                
            }
            $cnt++;
        }

        return $rePhotos;
        
    }
    
    public function isDevice($key){
                
        $httpUserAgent = $key->header('user_agent');
        if (preg_match('/(iPhone|Android.*Mobile|Windows.*Phone)/', $httpUserAgent)) {
            return true;
	}
        return false;
    }
    
