<h3 style="font-weight: bold;padding: .25em 0 .25em .75em;border-left: 6px solid #ccc;">ベルゲンから電車に乗れない</h3>
</br>

<p>ガイランゲルとは違い、今回はツアーでの行動となる為、他にも人がいて安心です。</p>
<p>本日も朝早く起床し駅のキオスクでコーヒーとサンドイッチで軽食を済ませます。</p>
<p>駅のインフォメーションセンターで日本で購入したチケットを確認します。</p>
<p>大丈夫でしたがベルゲン急行が工事の為、ベルゲンから電車に乗れないとのこと。。</p>
<p>少々残念ですが、途中までバスで行くことになりました。</p>
<p>駅は観光客で大変混雑していました。</p>
<p>乗るべきバスを聞いたり必死に探し、無事に乗り込むことに成功しました。</p>
<p>バスからの景色も良いんですが、そろそろ慣れてきました。</p>
