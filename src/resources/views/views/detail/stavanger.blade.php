<h3 style="font-weight: bold;padding: .25em 0 .25em .75em;border-left: 6px solid #ccc;">バスの時間まで魚市場へ</h3>
</br>
<p>朝早く起床しドミトリーを後にしました。</p>
<p>昨日確認したのですが結局どのバス停か分からなかったので、朝早く<a target="_blank" href="https://www.google.co.jp/maps/place/Bergen+busstasjon/@60.3871085,5.3318187,17z/data=!4m13!1m7!3m6!1s0x46390d4966767d77:0x9e42a03eb4de0a08!2z44OO44Or44Km44Kn44O8IOODmeODq-OCsuODsw!3b1!8m2!3d60.3912628!4d5.3220544!3m4!1s0x463cfeadcd1e2aeb:0x14a4c87d75260305!8m2!3d60.3873786!4d5.3351833">バスターミナル</a>へ行き確認しました。</p>
<p>(バス停の位置は一応リンクしときましたが、正確な位置ではなく、実際は建物の中です。)</p>
<p>事前調べと同様、出発は9:00だったので時間までベルゲンの魚市場を散歩しました。</p>
<p>(魚市場の位置は他のガイドブックを参照して下さい。)</p>
<p>おいしそうな海鮮魚類がたくさん売っているものの価格的にお手軽なものがなく結局何も食べませんでした。</p>
<p>(そのせいか魚市場の写真があまりない。。。)</p>


