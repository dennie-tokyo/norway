<p>電動自転車は最近レンタルしたようです。</p>
<p>自転車に乗るも、なんだか坂道が辛い。</p>
<p>と思ったら、自転車の受付のおねぇさんが後ろから走ってきて、電池を持ってきてくれました。</p>
<p>危うく電動ではなく人力で登るところでした。</p>


