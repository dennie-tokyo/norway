<p>観光案内所は予想以上に人が多く、余裕に思っていた自分が間違いでした。</p>
<p>ガイランゲルの目的はFlydalsjuvet(フリーダルスユーエ)の展望台と、Dalsnibba(ダレスニッパ)展望台です。</p>
<p>なんと、ダルスニッパ展望台のバスチケットが直近の時間では売り切れ。</p>
<p>次のバスの時間は微妙かなぁ～と思い、思い切って電動自転車で行くことにしました！！</p>

<div class="row">
<div class="col-sm-12">
