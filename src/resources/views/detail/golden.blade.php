<h3 style="font-weight: bold;padding: .25em 0 .25em .75em;border-left: 6px solid #ccc;">オンダルスネスでの奮闘</h3>
</br>

<p>大変なのはここからです。</p>
<p>今回の旅行計画で最大のミスで、こうなることは分かってましたが。。</p>
<p>ガイランゲル行きのバスがないのです！！</p>
<p>6月21日以降であればゴールデンルートと呼ばれるオンダルスネスからガイランゲル間のバスが運行するようで。。</p>
<p>ともあれ、行動します。 が、タクシーは出払ってるようで。。。</p>
<p>観光センターのおねぇさんにタクシーを呼びたいと伝えると、タクシーステーションへ行けと言われ。</p>
<p>タクシーステーションには無愛想で怖そうなおねぇさんがいました。</p>
<p>はなしかけると、タクシー会社の番号渡され、「ここへ電話しろ」とのこと。</p>
<p>英語で電話するにはハードルが高くオロオロ状態。</p>
<p>なので、観光センターのおねぇさんにタクシーを呼んでくれるようにメモとジェスチャーで交渉しました。</p>
<p>やった！！思いが通じた！！タクシー呼んでくれました！！</p>
<p>おねぇさんが天使に見えましたよ。</p>


